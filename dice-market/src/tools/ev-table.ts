// Regenerates src/shared/ev-table.ts from exact enumeration: npm run ev-table
import { writeFileSync } from 'node:fs';
import { UPGRADE_IDS, type UpgradeId } from '../shared/catalog.js';
import { resolveDice } from '../shared/dice.js';

/**
 * Exact mean as one integer sum over a common denominator 6^n * 36, divided once.
 * Each initial roll with k rerolls has 6^k equally likely continuations of weight 36 / 6^k.
 */
function exactMean(equipment: UpgradeId[]): { num: number; den: number; mean: number } {
  const n = equipment.includes('extra_die') ? 6 : 5;
  const original = new Array(n).fill(1);
  let num = 0;
  for (let code = 0; code < 6 ** n; code++) {
    let c = code;
    for (let i = 0; i < n; i++) {
      original[i] = (c % 6) + 1;
      c = Math.floor(c / 6);
    }
    let used = 0;
    resolveDice(equipment, () => (used < n ? original[used++] : (used++, 1)));
    const k = used - n;
    for (let rc = 0; rc < 6 ** k; rc++) {
      const reps = [(rc % 6) + 1, (Math.floor(rc / 6) % 6) + 1];
      let i = 0;
      num += resolveDice(equipment, () => (i < n ? original[i++] : reps[i++ - n])).payout * (36 / 6 ** k);
    }
  }
  const den = 6 ** n * 36;
  if (!Number.isSafeInteger(num)) throw new Error('exact sum overflowed');
  return { num, den, mean: num / den };
}

const sets: UpgradeId[][] = [[], ...UPGRADE_IDS.map((t) => [t])];
for (let i = 0; i < UPGRADE_IDS.length; i++) for (let j = i + 1; j < UPGRADE_IDS.length; j++) sets.push([UPGRADE_IDS[i], UPGRADE_IDS[j]]);

const rows = sets.map((s) => {
  const e = exactMean(s);
  return `  '${s.join('+')}': ${e.mean}, // ${e.num} / ${e.den}`;
});
const src = `// Generated by src/tools/ev-table.ts from exact enumeration (npm run ev-table). Do not edit by hand.
// test/ev-table.test.ts checks these values against the enumeration so they cannot drift.
import { UPGRADE_IDS, type UpgradeId } from './catalog.js';

/** Exact expected dice payout for each equipment set, keyed by catalog-ordered ids joined with '+'. */
export const MU: Record<string, number> = {
${rows.join('\n')}
};

function ordered(xs: UpgradeId[]): UpgradeId[] {
  return xs.slice().sort((a, b) => UPGRADE_IDS.indexOf(a) - UPGRADE_IDS.indexOf(b));
}

export function equipKey(xs: UpgradeId[]): string {
  return ordered(xs).join('+');
}

/** Expected payout of equipping exactly these types (at most two, distinct). */
export function mu(equipment: UpgradeId[]): number {
  const v = MU[equipKey([...new Set(equipment)])];
  if (v === undefined) throw new Error(\`no expected payout for \${equipment.join('+')}\`);
  return v;
}

/** The best equipment (at most two types) from an owned set, ties broken by catalog order. */
export function bestPair(owned: Iterable<UpgradeId>): UpgradeId[] {
  const s = ordered([...new Set(owned)]);
  let best: UpgradeId[] = [];
  let bestV = MU[''];
  const consider = (p: UpgradeId[]) => {
    const v = mu(p);
    if (v > bestV + 1e-12) {
      best = p;
      bestV = v;
    }
  };
  for (let i = 0; i < s.length; i++) consider([s[i]]);
  for (let i = 0; i < s.length; i++) for (let j = i + 1; j < s.length; j++) consider([s[i], s[j]]);
  return best;
}

/** V(S): the best expected payout available from owned set S. */
export function V(owned: Iterable<UpgradeId>): number {
  return mu(bestPair(owned));
}
`;
writeFileSync('src/shared/ev-table.ts', src);
console.log(`wrote src/shared/ev-table.ts (${sets.length} entries)`);
