// Generates docs/strategy/tables.tex from exact enumeration: npm run strategy-tables
import { mkdirSync, writeFileSync } from 'node:fs';
import { CATALOG, UPGRADE_IDS, type UpgradeId } from '../shared/catalog.js';
import { exactDistribution, stats } from './balance-lib.js';

const ids = UPGRADE_IDS;
const short: Record<UpgradeId, string> = {
  extra_die: 'ED',
  second_chance: 'SC',
  loaded_dice: 'LD',
  six_hunter: 'SH',
  jackpot: 'JP',
  safety_net: 'SN',
};
const order = (xs: UpgradeId[]) => xs.slice().sort((a, b) => ids.indexOf(a) - ids.indexOf(b));
const key = (xs: UpgradeId[]) => order(xs).join('+');

const mean = new Map<string, number>();
const sd = new Map<string, number>();
const tail = new Map<string, { p150: number; p200: number; max: number }>();
const sets: UpgradeId[][] = [[], ...ids.map((t) => [t])];
for (let i = 0; i < ids.length; i++) for (let j = i + 1; j < ids.length; j++) sets.push([ids[i], ids[j]]);
for (const s of sets) {
  const st = stats(s);
  mean.set(key(s), st.mean);
  sd.set(key(s), st.sd);
  const { dist } = exactDistribution(s);
  let p150 = 0;
  let p200 = 0;
  for (const [v, p] of dist) {
    if (v >= 150) p150 += p;
    if (v >= 200) p200 += p;
  }
  tail.set(key(s), { p150, p200, max: st.max });
}

/** V(S): best expected payout from equipping at most two types of S. */
function V(S: UpgradeId[]): number {
  let best = mean.get('')!;
  for (const a of S) best = Math.max(best, mean.get(key([a]))!);
  for (let i = 0; i < S.length; i++) for (let j = i + 1; j < S.length; j++) best = Math.max(best, mean.get(key([S[i], S[j]]))!);
  return best;
}

const f2 = (x: number) => (Math.abs(x) < 5e-5 ? 0 : x).toFixed(2);
const f4 = (x: number) => (Math.abs(x) < 5e-5 ? 0 : x).toFixed(4);
const nm = (s: UpgradeId[]) => (s.length ? order(s).map((t) => CATALOG[t].name).join(' + ') : 'No upgrade');
const out: string[] = ['% Generated by src/tools/strategy-tables.ts. Do not edit by hand.', ''];

// Table: singles and pairs ranked by mean
const ranked = sets.slice().sort((a, b) => mean.get(key(b))! - mean.get(key(a))!);
out.push('\\newcommand{\\TableRanked}{%');
out.push('\\begin{tabular}{lrrrrrr}');
out.push('\\toprule Equipment & $\\mu$ & $\\mu-\\mu_\\varnothing$ & $\\sigma$ & $\\Pr[\\ge150]$ & $\\Pr[\\ge200]$ & max \\\\ \\midrule');
for (const s of ranked) {
  const k = key(s);
  const t = tail.get(k)!;
  out.push(`${nm(s)} & ${f4(mean.get(k)!)} & ${f4(mean.get(k)! - mean.get('')!)} & ${f2(sd.get(k)!)} & ${f4(t.p150)} & ${f4(t.p200)} & ${t.max} \\\\`);
}
out.push('\\bottomrule\\end{tabular}}', '');

// Table: marginal value of acquiring B while holding exactly A
out.push('\\newcommand{\\TableMarginal}{%');
out.push(`\\begin{tabular}{l${'r'.repeat(ids.length)}}`);
out.push(`\\toprule Held $\\backslash$ Acquire & ${ids.map((t) => short[t]).join(' & ')} \\\\ \\midrule`);
out.push(`(nothing) & ${ids.map((b) => f2(V([b]) - V([]))).join(' & ')} \\\\`);
for (const a of ids) {
  out.push(`${CATALOG[a].name} & ${ids.map((b) => (a === b ? '$0$' : f2(V([a, b]) - V([a])))).join(' & ')} \\\\`);
}
out.push('\\bottomrule\\end{tabular}}', '');

// Table: best pair from each owned triple, and what the timeout fallback could cost
out.push('\\newcommand{\\TableTriples}{%');
out.push('\\begin{tabular}{lllr}');
out.push('\\toprule Owned & Best pair & Worst pair & Gap \\\\ \\midrule');
for (let i = 0; i < ids.length; i++)
  for (let j = i + 1; j < ids.length; j++)
    for (let k = j + 1; k < ids.length; k++) {
      const s = [ids[i], ids[j], ids[k]];
      const pairs = [
        [s[0], s[1]],
        [s[0], s[2]],
        [s[1], s[2]],
      ].sort((x, y) => mean.get(key(y))! - mean.get(key(x))!);
      const best = pairs[0];
      const worst = pairs[2];
      out.push(
        `${s.map((t) => short[t]).join(', ')} & ${best.map((t) => short[t]).join('+')} (${f2(mean.get(key(best))!)}) & ${worst.map((t) => short[t]).join('+')} (${f2(mean.get(key(worst))!)}) & ${f2(mean.get(key(best))! - mean.get(key(worst))!)} \\\\`,
      );
    }
out.push('\\bottomrule\\end{tabular}}', '');

const minMarg = Math.min(...ids.flatMap((a) => ids.filter((b) => b !== a).map((b) => V([a, b]) - V([a]))));
const maxMarg = Math.max(...ids.flatMap((a) => ids.filter((b) => b !== a).map((b) => V([a, b]) - V([a]))));
out.push(`\\newcommand{\\MaxMarginal}{${f2(maxMarg)}}`);
out.push(`\\newcommand{\\MinMarginal}{${f2(minMarg)}}`);
out.push(`\\newcommand{\\BasePayout}{${f4(mean.get('')!)}}`);
out.push(`\\newcommand{\\BestPairMean}{${f4(mean.get(key(ranked[0]))!)}}`);
out.push(`\\newcommand{\\BestPairName}{${nm(ranked[0])}}`);

// Largest marginal use value over every possible owned set S and every type t not in S.
let bestAll = { v: -Infinity, S: [] as UpgradeId[], t: ids[0] as UpgradeId };
for (let mask = 0; mask < 1 << ids.length; mask++) {
  const S = ids.filter((_, i) => mask & (1 << i));
  for (const t of ids) {
    if (S.includes(t)) continue;
    const v = V([...S, t]) - V(S);
    if (v > bestAll.v) bestAll = { v, S, t };
  }
}
out.push(`\\newcommand{\\MaxMarginalAll}{${f2(bestAll.v)}}`);
out.push(`\\newcommand{\\MaxMarginalAllWhere}{${CATALOG[bestAll.t].name} while holding ${bestAll.S.length ? nm(bestAll.S) : 'nothing'}}`);
let maxGap = 0;
for (let i = 0; i < ids.length; i++)
  for (let j = i + 1; j < ids.length; j++)
    for (let k = j + 1; k < ids.length; k++) {
      const s = [ids[i], ids[j], ids[k]];
      const ms = [mean.get(key([s[0], s[1]]))!, mean.get(key([s[0], s[2]]))!, mean.get(key([s[1], s[2]]))!];
      maxGap = Math.max(maxGap, Math.max(...ms) - Math.min(...ms));
    }
out.push(`\\newcommand{\\MaxTripleGap}{${f2(maxGap)}}`);
// Worst case of the selection-timeout rule: keep the starting upgrade if still owned,
// then fill from owned types in catalog order. Pools have four types, so |S| <= 4.
let worstFallback = { loss: 0, S: [] as UpgradeId[], start: null as UpgradeId | null, got: [] as UpgradeId[] };
for (let mask = 0; mask < 1 << ids.length; mask++) {
  const S = ids.filter((_, i) => mask & (1 << i));
  if (S.length > 4) continue;
  for (const start of [null, ...S]) {
    const got: UpgradeId[] = start ? [start] : [];
    for (const t of ids) if (got.length < 2 && S.includes(t) && !got.includes(t)) got.push(t);
    const loss = V(S) - (got.length === 0 ? mean.get('')! : mean.get(key(got))!);
    if (loss > worstFallback.loss + 1e-12) worstFallback = { loss, S, start, got };
  }
}
out.push(`\\newcommand{\\MaxFallbackLoss}{${f2(worstFallback.loss)}}`);
out.push(
  `\\newcommand{\\MaxFallbackWhere}{owning ${nm(worstFallback.S)} with ${worstFallback.start ? CATALOG[worstFallback.start].name : 'no'} as the starting upgrade, where the rule equips ${nm(worstFallback.got)}}`,
);
console.log('worst fallback', f2(worstFallback.loss), worstFallback);
console.log('max marginal over all S', f2(bestAll.v), bestAll.S, bestAll.t, 'max triple gap', f2(maxGap));

mkdirSync('docs/strategy', { recursive: true });
writeFileSync('docs/strategy/tables.tex', out.join('\n') + '\n');
console.log('wrote docs/strategy/tables.tex; max marginal', f2(maxMarg), 'min marginal', f2(minMarg));
